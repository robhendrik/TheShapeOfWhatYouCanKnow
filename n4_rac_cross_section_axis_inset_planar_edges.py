def main() -> None:
    log("Building n=4 RAC geometry...")

    vertices = build_vertices()

    log(f"      generated {len(vertices)} unique 4D points")
    log("")

    normal = np.asarray(SLICE_NORMAL, dtype=float)
    norm = np.linalg.norm(normal)

    if norm < TOL:
        raise ValueError("SLICE_NORMAL cannot be zero.")

    # Normalize the plane equation so multiplying SLICE_NORMAL by a scalar
    # does not change the geometric plane.
    normal = normal / norm
    offset = float(SLICE_OFFSET) / norm

    points3, points4, basis, hull3 = compute_section(
        vertices,
        normal,
        offset,
    )

    x0 = offset * normal

    log("")
    log("Slice basis vectors expressed in (c1,c2,c3,c4):")

    for i in range(3):
        log(f"  axis {i + 1}: {np.round(basis[:, i], 5)}")

    if PRINT_SECTION_VERTICES:
        log("")
        log("Section vertices in original (c1,c2,c3,c4) coordinates:")

        for point in points4:
            log(f"  {np.round(point, 6)}")

    log("")
    log("Rendering settings:")
    log(f"  opacity        = {OPACITY}")
    log("  edges          = reconstructed from merged coplanar faces")
    log(f"  plane tolerance = normal {COPLANAR_NORMAL_TOL:g}, offset {COPLANAR_OFFSET_TOL:g}")
    log(f"  camera         = {CAMERA_POSITION}")
    log(f"  axis inset     = right {AXIS_INSET_RIGHT}, up {AXIS_INSET_UP}")
    log(f"  key light      = {LIGHT_POSITION}")
    log(
        f"  fill light     = "
        f"{FILL_LIGHT_POSITION if USE_FILL_LIGHT else 'disabled'}"
    )
    log("")

    plot_section(points3, hull3, vertices, normal, offset, x0, basis)


if __name__ == "__main__":
    main()