def _normalized_hull_planes(hull3: ConvexHull):
    """Return unit facet normals and consistently scaled plane offsets."""
    equations = np.asarray(hull3.equations, dtype=float)
    normals = equations[:, :3].copy()
    offsets = equations[:, 3].copy()

    lengths = np.linalg.norm(normals, axis=1)
    normals /= lengths[:, None]
    offsets /= lengths

    return normals, offsets


def _group_coplanar_triangles(hull3: ConvexHull):
    """
    Group Qhull surface triangles that belong to the same mathematical plane.

    scipy.spatial.ConvexHull triangulates polygonal faces.  Comparing triangle
    normals locally (as vtkFeatureEdges does) can leave false diagonals because
    numerically coplanar triangles are not always represented by exactly equal
    normals.  Here we explicitly merge such triangles first.
    """
    normals, offsets = _normalized_hull_planes(hull3)
    groups = []

    for tri_id, (normal, offset) in enumerate(zip(normals, offsets)):
        matched = False

        for group in groups:
            ref_normal = group["normal"]
            ref_offset = group["offset"]

            # Qhull uses consistently outward-facing normals for a convex hull.
            # The abs fallback makes this robust even if an orientation ever
            # arrives reversed.
            same_orientation = np.linalg.norm(normal - ref_normal) <= COPLANAR_NORMAL_TOL
            opposite_orientation = np.linalg.norm(normal + ref_normal) <= COPLANAR_NORMAL_TOL

            if same_orientation:
                same_plane = abs(offset - ref_offset) <= COPLANAR_OFFSET_TOL
            elif opposite_orientation:
                same_plane = abs(offset + ref_offset) <= COPLANAR_OFFSET_TOL
            else:
                same_plane = False

            if same_plane:
                group["triangles"].append(tri_id)
                matched = True
                break

        if not matched:
            groups.append({
                "normal": normal.copy(),
                "offset": float(offset),
                "triangles": [tri_id],
            })

    return groups


def true_polytope_edges(hull3: ConvexHull) -> list[tuple[int, int]]:
    """
    Recover only boundaries between polygonal faces of the 3D section.

    For each coplanar triangle group, every triangulation diagonal occurs twice
    inside that group, while an edge on the boundary of the polygonal face
    occurs once.  Keeping the once-occurring edges therefore removes all
    diagonals that lie inside a plane.
    """
    groups = _group_coplanar_triangles(hull3)
    true_edges = set()

    for group in groups:
        counts = {}

        for tri_id in group["triangles"]:
            tri = hull3.simplices[tri_id]

            for a, b in (
                (int(tri[0]), int(tri[1])),
                (int(tri[1]), int(tri[2])),
                (int(tri[2]), int(tri[0])),
            ):
                edge = tuple(sorted((a, b)))
                counts[edge] = counts.get(edge, 0) + 1

        # Boundary edges of this planar polygon occur exactly once.
        for edge, count in counts.items():
            if count == 1:
                true_edges.add(edge)

    return sorted(true_edges)


def add_feature_edges(plotter, points3, hull3):
    """
    Draw true polytope edges after merging coplanar hull triangles.

    This deliberately does not use vtk/PyVista feature-angle extraction.
    """
    if not SHOW_EDGES:
        return

    edges = true_polytope_edges(hull3)

    if not edges:
        log("      Warning: no polytope edges were reconstructed.")
        return

    # PyVista line-cell format: [2, i, j, 2, i, j, ...]
    lines = np.asarray(
        [[2, i, j] for i, j in edges],
        dtype=np.int64,
    ).ravel()

    edge_mesh = pv.PolyData(np.asarray(points3, dtype=float))
    edge_mesh.lines = lines

    color = EDGE_COLOR if EDGE_COLOR is not None else "black"
    plotter.add_mesh(
        edge_mesh,
        color=color,
        line_width=EDGE_WIDTH,
        lighting=False,
    )

    log(
        f"      reconstructed {len(_group_coplanar_triangles(hull3))} "
        f"planar faces and {len(edges)} true edges"
    )


