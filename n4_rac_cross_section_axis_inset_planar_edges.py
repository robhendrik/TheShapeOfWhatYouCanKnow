def slice_basis(
    normal: np.ndarray,
    offset: float,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """
    Construct an orthonormal 3D coordinate system inside

        normal · x = offset.

    Returns
    -------
    n_hat
        Normalized hyperplane normal.
    x0
        Point on the hyperplane closest to the origin.
    basis
        4x3 orthonormal matrix spanning the hyperplane.
    """
    normal = np.asarray(normal, dtype=float)

    if normal.shape != (4,):
        raise ValueError("SLICE_NORMAL must have exactly four components.")

    length = np.linalg.norm(normal)

    if length < TOL:
        raise ValueError("SLICE_NORMAL cannot be the zero vector.")

    n_hat = normal / length
    d = float(offset) / length

    x0 = d * n_hat
    basis = null_space(n_hat.reshape(1, 4))

    if basis.shape != (4, 3):
        raise RuntimeError("Could not construct the 3D slice basis.")

    return n_hat, x0, basis


def candidate_edges_from_hull(hull: ConvexHull) -> list[tuple[int, int]]:
    """
    Extract candidate boundary edges from Qhull's triangulated 4D facets.

    Some candidates can be diagonals inside a non-simplicial facet.
    That is harmless: their intersection points disappear when we take
    the final 3D convex hull.
    """
    edges = set()

    for simplex in hull.simplices:
        for i in range(len(simplex)):
            for j in range(i + 1, len(simplex)):
                a, b = sorted((int(simplex[i]), int(simplex[j])))
                edges.add((a, b))

    return sorted(edges)


def section_points_from_edges(
    vertices: np.ndarray,
    edges: list[tuple[int, int]],
    normal: np.ndarray,
    offset: float,
) -> np.ndarray:
    """
    Intersect candidate hull edges with

        normal · x = offset.
    """
    signed_distance = vertices @ normal - offset
    points = []

    for i, j in edges:
        vi = vertices[i]
        vj = vertices[j]

        fi = signed_distance[i]
        fj = signed_distance[j]

        # Entire candidate edge lies in the plane.
        if abs(fi) <= TOL and abs(fj) <= TOL:
            points.extend((vi, vj))
            continue

        # One endpoint lies in the plane.
        if abs(fi) <= TOL:
            points.append(vi)
            continue

        if abs(fj) <= TOL:
            points.append(vj)
            continue

        # Edge crosses the plane.
        if fi * fj < 0.0:
            t = fi / (fi - fj)
            point = vi + t * (vj - vi)
            points.append(point)

    if not points:
        raise ValueError(
            "The selected hyperplane does not intersect the 4D polytope."
        )

    return unique_rows(np.asarray(points), decimals=9)


def to_slice_coordinates(
    points_4d: np.ndarray,
    x0: np.ndarray,
    basis: np.ndarray,
) -> np.ndarray:
    """Express R^4 points in the slice's 3D orthonormal coordinates."""
    return (points_4d - x0) @ basis


def compute_section(
    vertices: np.ndarray,
    normal: np.ndarray,
    offset: float,
) -> tuple[np.ndarray, np.ndarray, np.ndarray, ConvexHull]:
    """Compute the 3D cross-section and return its vertices and hull."""

    t0 = perf_counter()

    log("[1/5] Computing 4D convex hull...")
    hull4 = ConvexHull(vertices)

    log(
        f"      done: {len(vertices)} generating points, "
        f"{len(hull4.simplices)} triangulated boundary facets "
        f"({perf_counter() - t0:.3f} s)"
    )

    t1 = perf_counter()

    log("[2/5] Extracting candidate hull edges...")
    edges = candidate_edges_from_hull(hull4)

    log(
        f"      done: {len(edges)} candidate edges "
        f"({perf_counter() - t1:.3f} s)"
    )

    t2 = perf_counter()

    log("[3/5] Intersecting edges with 3D slice...")
    points4 = section_points_from_edges(
        vertices,
        edges,
        normal,
        offset,
    )

    log(
        f"      done: {len(points4)} unique intersection points "
        f"({perf_counter() - t2:.3f} s)"
    )

    _, x0, basis = slice_basis(normal, offset)
    points3 = to_slice_coordinates(points4, x0, basis)

    t3 = perf_counter()

    log("[4/5] Computing 3D convex hull of the section...")
    hull3_initial = ConvexHull(points3)

    # Remove candidate intersection points that are not actual hull vertices.
    surface_ids = np.unique(hull3_initial.simplices.ravel())
    points3_surface = points3[surface_ids]
    points4_surface = points4[surface_ids]

    hull3 = ConvexHull(points3_surface)

    log(
        f"      done: {len(points3_surface)} actual section vertices, "
        f"{len(hull3.simplices)} surface triangles "
        f"({perf_counter() - t3:.3f} s)"
    )

    return points3_surface, points4_surface, basis, hull3




