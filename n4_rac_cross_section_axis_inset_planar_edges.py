VERTEX_TYPE_PROTOTYPES = {
    "axis type (1,0,0,0)": np.array([1.0, 0.0, 0.0, 0.0]),
    "3/4 + 1/4 type": np.array([0.75, 0.25, 0.25, 0.25]),
    "1/2 + 1/2 + 1/2 type": np.array([0.5, 0.5, 0.5, 0.0]),
}

