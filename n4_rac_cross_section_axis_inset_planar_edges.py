def make_mesh(
    points3: np.ndarray,
    hull3: ConvexHull,
) -> pv.PolyData:
    """Convert scipy's triangular hull surface to PyVista PolyData."""

    triangles = hull3.simplices.astype(np.int64)

    faces = np.column_stack(
        (
            np.full(len(triangles), 3, dtype=np.int64),
            triangles,
        )
    ).ravel()

    return pv.PolyData(points3, faces)


def configure_lighting(plotter: pv.Plotter) -> None:
    """Apply reproducible custom lighting."""

    if not USE_CUSTOM_LIGHTING:
        return

    plotter.remove_all_lights()

    key_light = pv.Light(
        position=LIGHT_POSITION,
        focal_point=LIGHT_FOCAL_POINT,
        intensity=LIGHT_INTENSITY,
    )
    plotter.add_light(key_light)

    if USE_FILL_LIGHT:
        fill_light = pv.Light(
            position=FILL_LIGHT_POSITION,
            focal_point=FILL_LIGHT_FOCAL_POINT,
            intensity=FILL_LIGHT_INTENSITY,
        )
        plotter.add_light(fill_light)


def configure_camera(plotter: pv.Plotter) -> None:
    """Apply a fixed reproducible camera."""

    plotter.camera.position = CAMERA_POSITION
    plotter.camera.focal_point = CAMERA_FOCAL_POINT
    plotter.camera.up = CAMERA_UP

    if PARALLEL_PROJECTION:
        plotter.enable_parallel_projection()
    else:
        plotter.disable_parallel_projection()

    if CAMERA_ZOOM != 1.0:
        plotter.camera.zoom(CAMERA_ZOOM)



def slice_equation_label(normal, offset):
    """Human-readable hyperplane label for simple coordinate slices."""
    nz = np.flatnonzero(np.abs(normal) > 1e-8)
    if len(nz) == 1 and abs(abs(normal[nz[0]]) - 1.0) < 1e-8:
        i = int(nz[0])
        value = offset / normal[i]
        return f"slice: c{i+1} = {value:g}"
    return f"slice: n·c = {offset:g}"


def plot_section(
    points3: np.ndarray,
    hull3: ConvexHull,
    vertices4: np.ndarray,
    normal: np.ndarray,
    offset: float,
    x0: np.ndarray,
    basis: np.ndarray,
) -> None:
    """Render the section interactively with PyVista."""

    log("[5/5] Opening PyVista window...")
    log("      Close the PyVista window to return to PowerShell.")

    mesh = make_mesh(points3, hull3)
    plotter = pv.Plotter(window_size=WINDOW_SIZE)
    plotter.set_background(BACKGROUND)
    configure_lighting(plotter)

    mesh_kwargs = dict(
        opacity=OPACITY,
        show_edges=False,
        smooth_shading=SMOOTH_SHADING,
        label="n=4 classical section",
    )
    if OBJECT_COLOR is not None:
        mesh_kwargs["color"] = OBJECT_COLOR
    if EDGE_COLOR is not None:
        mesh_kwargs["edge_color"] = EDGE_COLOR
    plotter.add_mesh(mesh, **mesh_kwargs)
    add_feature_edges(plotter, points3, hull3)

    if SHOW_SECTION_VERTICES:
        plotter.add_mesh(pv.PolyData(points3), point_size=SECTION_VERTEX_SIZE,
                         render_points_as_spheres=True, label="section vertices")

    if SHOW_ORIGINAL_VERTICES:
        add_original_vertices(plotter, vertices4, normal, offset, x0, basis)

    if SHOW_PROJECTED_AXES:
        add_projected_axes(plotter, normal, basis)

    if SHOW_WINNING_DIRECTION:
        add_winning_direction(plotter, normal, basis)

    if SHOW_AXES:
        plotter.add_axes(xlabel="slice axis 1", ylabel="slice axis 2", zlabel="slice axis 3")

    if SHOW_TITLE:
        plotter.add_title(
            "n=4 advantage-space cross-section\n"
            f"normal={tuple(np.asarray(SLICE_NORMAL, dtype=float))}, "
            f"offset={SLICE_OFFSET:g}  ({slice_equation_label(normal, offset)})",
            font_size=11,
        )

    if SHOW_LEGEND:
        plotter.add_legend()

    # Configure the camera BEFORE creating the inset, because the inset
    # position is defined in camera-relative screen directions.
    configure_camera(plotter)

    if SHOW_AXIS_INSET:
        add_axis_inset(plotter, normal, basis)

    if SCREENSHOT:
        plotter.show(screenshot=SCREENSHOT)
    else:
        plotter.show()


