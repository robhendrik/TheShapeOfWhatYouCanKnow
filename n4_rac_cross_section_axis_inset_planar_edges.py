def log(msg: str) -> None:
    print(msg, flush=True)


def unique_rows(points: np.ndarray, decimals: int = 10) -> np.ndarray:
    """Remove duplicate rows using rounded coordinates."""
    points = np.asarray(points, dtype=float)
    rounded = np.round(points, decimals)
    _, idx = np.unique(rounded, axis=0, return_index=True)
    return points[np.sort(idx)]


def symmetry_orbit(prototype: np.ndarray) -> np.ndarray:
    """
    Generate coordinate permutations and independent coordinate sign flips.
    """
    points = []

    for perm in set(permutations(prototype.tolist())):
        p = np.asarray(perm, dtype=float)

        for signs in product((-1.0, 1.0), repeat=4):
            points.append(p * np.asarray(signs, dtype=float))

    return unique_rows(np.asarray(points))


def build_vertices() -> np.ndarray:
    """Return all symmetry-completed generating points."""
    points = np.vstack([symmetry_orbit(p) for p in PROTOTYPES])
    return unique_rows(points)


