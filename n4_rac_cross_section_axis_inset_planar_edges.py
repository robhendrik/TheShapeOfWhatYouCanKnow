"""
n=4 RAC advantage-space cross-section
======================================

Builds the symmetry-completed 4D polytope generated by the two n=4
vertex classes documented in the RAC Geometry project notes, takes an
arbitrary 3D affine cross-section,

    SLICE_NORMAL · c = SLICE_OFFSET,

and renders that section with PyVista.

Dependencies
------------
pip install numpy scipy pyvista

Scope
-----
The project notes document two n=4 vertex classes for the optimal
classical tie-strategy structure:

    degree type (3,1,1,1)  -> advantage prototype (3,1,1,1)/4
    degree type (2,2,2,0)  -> advantage prototype (2,2,2,0)/4

This script closes those prototypes under coordinate permutations and
independent sign flips, then takes their convex hull.

It therefore visualizes the symmetry-completed polytope generated by
those documented n=4 vertex classes. It should not be read, without an
additional proof, as an enumeration of every vertex of the completely
unrestricted one-bit classical RAC body.
"""

